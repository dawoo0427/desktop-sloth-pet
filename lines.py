def _time_slot(h):
    if h < 5:
        return "dawn"
    if h < 11:
        return "morning"
    if h < 14:
        return "noon"
    if h < 18:
        return "afternoon"
    if h < 22:
        return "evening"
    return "night"


def _season(m):
    return {3: "spring", 4: "spring", 5: "spring", 6: "summer", 7: "summer", 8: "summer",
            9: "autumn", 10: "autumn", 11: "autumn"}.get(m, "winter")


def _weather_keys(weather):
    """pet.py 날씨 한 줄("서울 약한 비 12°C (바람 ..)")에서 상황 키 뽑기."""
    keys = []
    if not weather:
        return keys
    if "눈" in weather:
        keys.append("snow")
    elif "비" in weather or "소나기" in weather or "뇌우" in weather:
        keys.append("rain")
    elif "맑" in weather:
        keys.append("clear")
    elif "흐림" in weather or "안개" in weather:
        keys.append("cloudy")
    m = re.search(r"(-?\d+)°C", weather)
    if m:
        t = int(m.group(1))
        if t >= 28:
            keys.append("hot")
        elif t <= 3:
            keys.append("cold")
    return keys


def _opener(now, weather):
    pools = [OPEN_TIME[_time_slot(now.tm_hour)]] * 3 + [OPEN_WEEKDAY[now.tm_wday]]
    pools += [OPEN_WEATHER[k] for k in _weather_keys(weather)] * 2
    if random.random() < 0.15:
        pools.append(OPEN_SEASON[_season(now.tm_mon)])
    return random.choice(random.choice(pools))


def _build(mood, now, weather):
    core = random.choice(MOOD_CORE.get(mood) or CORE)
    if mood in MOOD_CORE and random.random() < 0.25:
        return core + " " + random.choice(TAIL)
    if mood in MOOD_CORE:
        return core
    r = random.random()
    if r < 0.3:
        return core
    if r < 0.6:
        return _opener(now, weather) + " " + core
    if r < 0.85:
        return core + " " + random.choice(TAIL)
    return _opener(now, weather) + " " + core + " " + random.choice(TAIL)


def compose(mood="idle", weather=""):
    """상황에 맞는 새 대사 한 줄. weather = pet.py 의 최근 날씨 문자열(없으면 빈 값)."""
    now = time.localtime()
    for _ in range(12):
        s = _build(mood, now, weather)
        if len(s) <= MAX_LEN and s not in _recent:
            break
    _recent.append(s)
    return s


def piece_count():
    groups = [CORE, TAIL] + list(MOOD_CORE.values()) + list(OPEN_TIME.values()) + OPEN_WEEKDAY \
        + list(OPEN_WEATHER.values()) + list(OPEN_SEASON.values())
    return sum(len(g) for g in groups)
